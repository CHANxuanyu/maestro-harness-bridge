import { describe, expect, it } from 'vitest';
import { reduceLedger } from '../../../shared/team/ledger';
import { formatTeamStatus, teamStatus } from '../../../shared/team/status';
import { DURATION_MS } from '../../../shared/duration';
import { baseline, check, config, ledger, proven } from './fixtures';

describe('team status', () => {
	it('reports facts, missing reasons, work, waits, cards, budget and seat health without PM', () => {
		const state = reduceLedger(
			ledger(
				{ kind: 'team_created', config: { ...config, deadline: 1000 + DURATION_MS.hour } },
				...baseline.slice(1),
				check,
				{
					kind: 'member_fault',
					seat: 'pm',
					fault: 'session-broken',
					detail: 'Missing native session',
				},
				{ kind: 'work_item', itemId: 'w1', owner: 'dev', title: 'Parser', state: 'done' },
				{ kind: 'work_item', itemId: 'w2', owner: 'qa', title: 'Samples', state: 'checked' },
				{
					kind: 'follow_up_registered',
					followUpId: 'f1',
					seat: 'qa',
					waitFor: 'CI #42',
					reason: 'Queued',
				},
				{
					kind: 'decision_card',
					card: {
						id: 'c1',
						boundary: 'login',
						title: 'Registry login',
						body: 'Owner must log in',
						options: [],
					},
				},
				{ kind: 'turn_dispatched', seat: 'dev', dispatchId: 't1', turn: 'work', promptDigest: 'd1' }
			)
		);
		const view = teamStatus(state, 1000);
		expect(view).toMatchObject({
			generatedBy: 'app',
			criteria: { total: 3, withEvidence: 1 },
			budget: { turnsUsed: 1, turnsTotal: 40, remainingMs: DURATION_MS.hour, exhausted: false },
		});
		expect(view.criteria.missing.map((c) => c.id)).toEqual(['A2', 'E1']);
		expect(view.openWorkItems.map((w) => w.itemId)).toEqual(['w1']);
		expect(view.seats.find((s) => s.seat === 'pm')).toMatchObject({
			status: 'fault',
			lastFault: 'session-broken',
		});
		const text = formatTeamStatus(view);
		for (const value of [
			'generated by the app',
			'Phase: clarify',
			'1/3',
			'A2 [unproven]',
			'E1 [unproven]',
			'w1 (dev, done)',
			'CI #42',
			'c1 [login]',
			'1/40 turns',
			'1h',
			'pm: fault',
			'dev: working',
		])
			expect(text).toContain(value);
		expect(text).not.toContain('w2');
	});
	it('does not count unconfirmed criteria, and exposes an idle scheduler rather than pretending to work', () => {
		const view = teamStatus(reduceLedger(ledger(...baseline.slice(0, 2))), 0);
		expect(view.criteria.total).toBe(0);
		expect(formatTeamStatus(view)).toContain('No confirmed baseline');
		expect(view.waitingFor).toContain(
			'Scheduler to wake the PM; no member is working and no wait is registered.'
		);
	});
	it('does not extend a deadline during a pause and labels exhaustion as an incomplete report', () => {
		const events = ledger(
			{ kind: 'team_created', config: { ...config, deadline: 10 } },
			{ kind: 'paused' }
		);
		const paused = teamStatus(reduceLedger(events), 11);
		expect(paused.budget).toMatchObject({ remainingMs: 0, exhausted: true });
		expect(formatTeamStatus(paused)).toContain('Paused');
		const exhausted = teamStatus(
			reduceLedger(ledger({ kind: 'team_created', config: { ...config, turnBudget: 0 } })),
			11
		);
		expect(formatTeamStatus(exhausted)).toContain(
			'incomplete progress report, not a completion demo'
		);
	});
	it('keeps gaps visible, formats terminal states, and does not mutate replay state', () => {
		for (const terminal of ['all', 'gaps', 'stopped'] as const) {
			const state = reduceLedger(
				ledger(...(terminal === 'all' ? proven : baseline), {
					kind: 'terminal',
					terminal,
					residual: terminal === 'all' ? [] : ['A2 incomplete\nfollow up'],
				})
			);
			const before = structuredClone(state);
			const text = formatTeamStatus(teamStatus(state, 10));
			expect(text).toContain(
				terminal === 'all'
					? 'Accepted: all criteria met'
					: terminal === 'gaps'
						? 'Accepted with 1 residual item'
						: 'Stopped: incomplete'
			);
			if (terminal !== 'all') expect(text).toContain('A2 incomplete follow up');
			expect(state).toEqual(before);
		}
	});
});
