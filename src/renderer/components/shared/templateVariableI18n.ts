/** Localize the explanation, never the variable or substituted content. */
export function templateVariableDescription(
	variable: string,
	description: string,
	t: TFunction
): string {
	const key = TEMPLATE_DESCRIPTION_KEYS[variable as keyof typeof TEMPLATE_DESCRIPTION_KEYS];
	return key && description === translate('en', key) ? t(key) : description;
}
