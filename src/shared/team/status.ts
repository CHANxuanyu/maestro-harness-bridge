import { formatDurationCompact } from '../duration';
import { formatCost, formatTokens } from '../formatters';
import { DEFAULT_TEAM_TURN_BUDGET, SEAT_ROLES, type TeamState, type TeamStatusView } from './types';

/** App-owned status works even when no member, including the PM, can answer. */
export function teamStatus(state: TeamState, now: number): TeamStatusView {
	const criteria = state.criteria.filter((criterion) => criterion.confirmed);
	const deadline = state.config?.deadline;
	const remainingMs = deadline === undefined ? undefined : Math.max(0, deadline - now);
	const turnsTotal = state.config?.turnBudget ?? DEFAULT_TEAM_TURN_BUDGET;
	const waitingFor = state.followUps.map(
		(wait) => `${wait.seat}: ${wait.waitFor} (${wait.reason})`
	);
	for (const seat of SEAT_ROLES) {
		const health = state.seats[seat];
		if (health.faultActive && !health.takeover)
			waitingFor.push(`${seat}: recovery from ${health.lastFault?.fault ?? 'member fault'}`);
		if (health.quota && !health.takeover)
			waitingFor.push(
				`${seat}: quota recovery${health.quota.resetsAt === undefined ? '' : ` at ${new Date(health.quota.resetsAt).toISOString()}`}`
			);
	}
	for (const message of state.pendingMessages)
		waitingFor.push(`${message.to ?? 'pm'}: delivery of owner message ${message.messageId}`);
	if (!state.terminal) {
		if (state.paused) waitingFor.push('Owner to resume the team.');
		else if (state.usage.turns >= turnsTotal || remainingMs === 0)
			waitingFor.push(
				'Budget exhausted: owner decision on an incomplete progress report, not a completion demo.'
			);
		else if (
			!state.openCards.length &&
			!waitingFor.length &&
			!SEAT_ROLES.some((seat) => state.seats[seat].activeDispatchIds.length)
		)
			waitingFor.push('Scheduler to wake the PM; no member is working and no wait is registered.');
	}
	return {
		generatedBy: 'app',
		title: state.config?.title ?? 'Team',
		phase: state.phase,
		paused: state.paused,
		stopped: state.stopped,
		terminal: state.terminal,
		residual: [...state.residual],
		criteria: {
			total: criteria.length,
			withEvidence: criteria.filter((c) => c.status === 'pass').length,
			missing: criteria
				.filter((c) => c.status !== 'pass')
				.map(({ id, text, status, reason }) => ({ id, text, status, reason })),
		},
		openWorkItems: state.workItems.filter((item) => item.state !== 'checked'),
		waitingFor,
		openCards: [...state.openCards],
		budget: {
			turnsUsed: state.usage.turns,
			turnsTotal,
			deadline,
			remainingMs,
			exhausted: state.usage.turns >= turnsTotal || remainingMs === 0,
		},
		seats: SEAT_ROLES.map((seat) => {
			const health = state.seats[seat];
			return {
				seat,
				status:
					health.faultActive && !health.takeover
						? 'fault'
						: health.activeDispatchIds.length
							? 'working'
							: (health.quota && !health.takeover) || state.followUps.some((f) => f.seat === seat)
								? 'waiting'
								: health.binding
									? 'ready'
									: 'unbound',
				model: health.model,
				lastFault: health.lastFault?.fault,
				detail: health.lastFault?.detail,
				takeover: health.takeover,
				usage: { ...health.usage },
			};
		}),
		usage: { ...state.usage },
	};
}

/** Plain text for the CLI; flatten member-authored newlines to keep each reason on one line. */
export function formatTeamStatus(view: TeamStatusView): string {
	const line = (value: string) => value.replace(/\s+/g, ' ').trim();
	const outcome =
		view.terminal === 'all'
			? 'Accepted: all criteria met'
			: view.terminal === 'gaps'
				? `Accepted with ${view.residual.length} residual item(s)`
				: view.terminal === 'stopped'
					? 'Stopped: incomplete'
					: view.paused
						? 'Paused'
						: 'Active';
	return [
		`${line(view.title)} - generated by the app from the ledger`,
		`Phase: ${view.phase} | ${outcome}`,
		`Criteria with passing evidence: ${view.criteria.withEvidence}/${view.criteria.total}`,
		...view.criteria.missing.map((c) => `  ${line(c.id)} [${c.status}]: ${line(c.reason)}`),
		...(view.criteria.total === 0 ? ['  No confirmed baseline.'] : []),
		'Open work items:',
		...(view.openWorkItems.length
			? view.openWorkItems.map(
					(item) => `  ${line(item.itemId)} (${item.owner}, ${item.state}): ${line(item.title)}`
				)
			: ['  None']),
		'Waiting for:',
		...(view.waitingFor.length ? view.waitingFor.map((wait) => `  ${line(wait)}`) : ['  None']),
		`Open owner cards: ${view.openCards.length}`,
		...view.openCards.map(
			(card) => `  ${line(card.id)} [${card.boundary}]: ${line(card.title)} - ${line(card.body)}`
		),
		`Budget: ${view.budget.turnsUsed}/${view.budget.turnsTotal} turns${view.budget.remainingMs === undefined ? '; no deadline' : `; ${formatDurationCompact(view.budget.remainingMs)} to deadline`}${view.budget.exhausted ? '; exhausted' : ''}`,
		`Usage: ${formatTokens(view.usage.inputTokens)} input, ${formatTokens(view.usage.outputTokens)} output tokens; ${formatCost(view.usage.costUsd)} recorded cost (${view.usage.turnsWithCost}/${view.usage.turns} turns reported cost)`,
		'Seat health:',
		...view.seats.map(
			(seat) =>
				`  ${seat.seat}: ${seat.status}${seat.takeover ? `; ${seat.takeover} takeover active` : ''}${seat.lastFault ? `; last fault ${seat.lastFault}${seat.detail ? ` (${line(seat.detail)})` : ''}` : ''}; ${seat.usage.turns} turns`
		),
		...(view.residual.length
			? ['Residual items:', ...view.residual.map((item) => `  ${line(item)}`)]
			: []),
	].join('\n');
}
